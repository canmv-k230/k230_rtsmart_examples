#!/usr/bin/env python3
"""Generate test_pkc_vectors.h for test_pkc_hw.c.

RSA: one key per size (1024-4096), e = 65537, a random message m < n and the
raw signature m^d mod n. ECDSA: a P-384 (SHA-384) and a P-521 (SHA-512)
signature over a fixed digest, with the public key. CCM: AES-128-CCM with 20
bytes of AAD, used to check that split AAD gives the same result as one-shot
AAD.

The checked-in header is the canonical fixture. Regenerating changes the
random RSA/ECDSA vectors (CCM is deterministic); only regenerate when the
fixtures need to change. Requires Python 3 and cryptography.

Run: python3 host/gen_pkc_vectors.py > test_pkc_vectors.h
"""
import secrets

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec, rsa, utils
from cryptography.hazmat.primitives.ciphers.aead import AESCCM


def c_array(name, data):
    lines = [f"static const uint8_t {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    out = ["/* Generated by host/gen_pkc_vectors.py; do not edit. */",
           "#ifndef TEST_PKC_VECTORS_H", "#define TEST_PKC_VECTORS_H", "",
           "#include <stdint.h>", ""]
    for bits in (1024, 2048, 3072, 4096):
        key = rsa.generate_private_key(public_exponent=65537, key_size=bits)
        priv = key.private_numbers()
        n, d = priv.public_numbers.n, priv.d
        elen = bits // 8
        m = secrets.randbelow(n - 2) + 2
        sig = pow(m, d, n)
        assert pow(sig, 65537, n) == m
        for label, value in (("n", n), ("d", d), ("m", m), ("sig", sig)):
            out.append(c_array(f"rsa{bits}_{label}", value.to_bytes(elen, "big")))
        out.append("")

    for name, curve, hash_alg in (("p384", ec.SECP384R1(), hashes.SHA384()),
                                  ("p521", ec.SECP521R1(), hashes.SHA512())):
        qlen = (curve.key_size + 7) // 8
        digest = bytes((0x31 * i + 7) & 0xff for i in range(hash_alg.digest_size))
        key = ec.generate_private_key(curve)
        der = key.sign(digest, ec.ECDSA(utils.Prehashed(hash_alg)))
        r, s = utils.decode_dss_signature(der)
        pub = key.public_key().public_numbers()
        for label, value in (("qx", pub.x), ("qy", pub.y), ("r", r), ("s", s)):
            out.append(c_array(f"ecdsa_{name}_{label}", value.to_bytes(qlen, "big")))
        out.append(c_array(f"ecdsa_{name}_md", digest))
        out.append("")

    key = bytes(range(0x40, 0x50))
    nonce = bytes([0xa5] * 7)
    aad = bytes(range(0x60, 0x74))
    pt = bytes(range(0x10, 0x28))
    ct_tag = AESCCM(key, tag_length=8).encrypt(nonce, pt, aad)
    for label, value in (("key", key), ("nonce", nonce), ("aad", aad), ("pt", pt),
                         ("ct", ct_tag[:-8]), ("tag", ct_tag[-8:])):
        out.append(c_array(f"ccm_{label}", value))
    out += ["", "#endif"]
    print("\n".join(out))


if __name__ == "__main__":
    main()
